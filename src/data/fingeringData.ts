export interface FingeringNote {
  id: string;
  writtenNote: string;
  writtenOctave: number;
  concertPitch: string;
  concertOctave: number;
  freqHz: number;
  valves: number[]; // e.g. [1, 2], [4], [] for open
  valveLabel: string;
  alternateValves?: { valves: number[]; label: string; reason: string }[];
  slidePosition?: number; // for trombone (1 to 7)
  slideLabel?: string;
  alternateSlidePositions?: { position: number; label: string; reason: string }[];
  fAttachmentPosition?: number; // for bass trombone F-attachment
  partialNumber: number;
  register: 'pedal' | 'low' | 'middle' | 'high' | 'extreme';
  intonationTendency: 'in-tune' | 'sharp' | 'flat' | 'very-sharp' | 'very-flat';
  intonationAdvice: string;
  techniqueTip?: string;
}

export interface InstrumentFingeringProfile {
  id: string;
  name: string;
  family: 'horn' | 'trombone' | 'euphonium' | 'bass-eb' | 'bass-bb' | 'soprano' | 'cornet';
  fundamentalKey: 'Bb' | 'Eb';
  clef: 'treble' | 'bass' | 'dual';
  transpositionRule: string;
  soundingInterval: string;
  valveCount: 3 | 4 | 'slide' | 'slide-trigger';
  audioTimbre: 'cornet' | 'horn' | 'euphonium' | 'bass' | 'trombone';
  overview: string;
  mechanicsDescription: string;
  pedalAndLowNotesNote?: string;
  notes: FingeringNote[];
}

